function summary = summarize(metrics)
controllers = ["A";"A";"D";"D";"RL75";"RL75"];
axes = repmat(["lateral";"sagittal"],3,1);
recoveredCount=zeros(6,1); uprightCount=zeros(6,1); fallCount=zeros(6,1);
maxEither=nan(6,1); maxBidirectional=nan(6,1);
for index=1:6
    selected=metrics.Controller==controllers(index) & ...
        metrics.Axis==axes(index);
    recoveredCount(index)=nnz(metrics.Outcome(selected)=="recovered");
    uprightCount(index)=nnz( ...
        metrics.Outcome(selected)=="upright_not_recovered");
    fallCount(index)=nnz(metrics.Outcome(selected)=="fell");
    recoveredForces=abs(metrics.SignedForce_N(selected & metrics.Recovered));
    if ~isempty(recoveredForces); maxEither(index)=max(recoveredForces); end
    levels=unique(abs(metrics.SignedForce_N(selected)));
    bidirectional=false(size(levels));
    for levelIndex=1:numel(levels)
        atLevel=selected & abs(metrics.SignedForce_N)==levels(levelIndex);
        bidirectional(levelIndex)=nnz(atLevel)==2 && ...
            all(metrics.Recovered(atLevel));
    end
    if any(bidirectional)
        maxBidirectional(index)=max(levels(bidirectional));
    end
end
summary=table(controllers,axes,recoveredCount,uprightCount,fallCount, ...
    maxEither,maxBidirectional,'VariableNames', ...
    {'Controller','Axis','RecoveredCaseCount', ...
    'UprightNotRecoveredCaseCount','FallCaseCount', ...
    'MaximumEitherDirectionRecoveredForce_N', ...
    'MaximumBidirectionallyRecoveredForce_N'});
end
