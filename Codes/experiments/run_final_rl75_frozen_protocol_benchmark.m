function results = run_final_rl75_frozen_protocol_benchmark( ...
        existingRLEvidenceDirectory, baselineResultDirectory, outputRoot)
%RUN_FINAL_RL75_FROZEN_PROTOCOL_BENCHMARK Consolidate A, D and RL75.
%   Reuses the completed A/D evidence from the final 12 s benchmark and
%   simulates only frozen deterministic RL75 under exactly the same signed
%   force grid and protocol. No controller or model is retuned or saved.

arguments
    existingRLEvidenceDirectory (1,1) string = ""
    baselineResultDirectory (1,1) string = fullfile( ...
        project_codes_root(), "Results", ...
        "FormalFrozenControllerRobustness", "20260804_153609")
    outputRoot (1,1) string = fullfile( ...
        project_codes_root(), "Results", ...
        "FinalADRL75FrozenProtocolBenchmark")
end

baselineFile = fullfile(baselineResultDirectory,"processed_results.mat");
assert(isfile(baselineFile),"FinalBenchmark:BaselineEvidenceMissing", ...
    "Completed A/D benchmark was not found: %s",baselineFile);
baseline = load(baselineFile,"metrics","protocol");
frozenProtocol = frozen_robustness_protocol();
assertProtocolsMatch(baseline.protocol,frozenProtocol);

stamp = string(datetime("now","Format","yyyyMMdd_HHmmss"));
resultDirectory = fullfile(outputRoot,stamp);
mkdir(resultDirectory);
rlRoot = fullfile(resultDirectory,"rl75_simulations");

fprintf("\nFinal frozen-protocol A-D-RL75 benchmark\n");
fprintf("Reusing A/D evidence: %s\n",baselineResultDirectory);
if strlength(existingRLEvidenceDirectory)==0
    fprintf("Running only RL75: 1 nominal + 14 signed disturbances\n");
else
    fprintf("Consolidating previously completed RL75 simulations\n");
end
fprintf("Protocol: %g s horizon, %g s pulse at %g s\n", ...
    frozenProtocol.stopTime_s,frozenProtocol.pulseDuration_s, ...
    frozenProtocol.pulseStart_s);
fprintf("Output: %s\n\n",resultDirectory);

if strlength(existingRLEvidenceDirectory)==0
    rlRun = analyze_benchmark_protocol_sensitivity(rlRoot,"rl75_final");
else
    rlFile=fullfile(existingRLEvidenceDirectory,"processed_results.mat");
    assert(isfile(rlFile),"FinalBenchmark:RLEvidenceMissing", ...
        "Saved RL75 processed result was not found: %s",rlFile);
    loadedRL=load(rlFile,"primaryMetrics","protocol","provenance", ...
        "preflight","trajectories");
    assert(isfield(loadedRL,"primaryMetrics"), ...
        "FinalBenchmark:RLMetricsMissing", ...
        "Saved RL75 evidence does not contain primaryMetrics.");
    assertProtocolsMatch(loadedRL.protocol,frozenProtocol);
    rlRun=loadedRL;
    rlRun.resultDirectory=existingRLEvidenceDirectory;
    fprintf("Reusing completed RL75 evidence: %s\n", ...
        existingRLEvidenceDirectory);
end
rlMetrics = rlRun.primaryMetrics( ...
    rlRun.primaryMetrics.Horizon_s==frozenProtocol.stopTime_s & ...
    rlRun.primaryMetrics.SignedForce_N~=0,:);

adCore = standardizeAD(baseline.metrics);
rlCore = standardizeRL(rlMetrics);
metrics = [adCore;rlCore];
metrics = sortrows(metrics,["Controller","Axis","SignedForce_N"]);
summary = summarize(metrics);

writetable(metrics,fullfile(resultDirectory,"final_controller_metrics.csv"));
writetable(summary,fullfile(resultDirectory,"final_controller_summary.csv"));
save(fullfile(resultDirectory,"processed_results.mat"), ...
    "metrics","summary","frozenProtocol","baselineResultDirectory", ...
    "rlRun","-v7.3");

results = struct("resultDirectory",string(resultDirectory), ...
    "metrics",metrics,"summary",summary,"protocol",frozenProtocol, ...
    "baselineResultDirectory",baselineResultDirectory, ...
    "rl75EvidenceDirectory",rlRun.resultDirectory);

fprintf("\nFinal consolidated metrics:\n");
disp(metrics(:,["Controller","Axis","SignedForce_N","Outcome", ...
    "RecoveryTime_s","LateAxisDisplacementRMS_m", ...
    "LateAxisTiltRMS_deg","ActuatorSaturation"]));
fprintf("\nFinal controller/axis summary:\n");
disp(summary);
fprintf("Results written to %s\n",resultDirectory);
end

function assertProtocolsMatch(actual,expected)
fields = ["lateralForceLevels_N","sagittalForceLevels_N", ...
    "pulseStart_s","pulseDuration_s","stopTime_s","finalDwell_s", ...
    "recoveryTimeDwell_s","fallVerticalDrop_m", ...
    "fallHorizontalTravel_m","fallRotation_deg", ...
    "recoveryDisplacementRMS_m","recoveryTiltRMS_deg", ...
    "recoveryVelocityRMS_m_s","settlingRatioLimit", ...
    "smallDisplacementRMS_m","smallTiltRMS_deg"];
for name = fields
    assert(isfield(actual,name),"FinalBenchmark:ProtocolFieldMissing", ...
        "A/D evidence lacks protocol field %s.",name);
    assert(isequal(actual.(name),expected.(name)), ...
        "FinalBenchmark:ProtocolMismatch", ...
        "A/D protocol field %s does not match the frozen protocol.",name);
end
end

function core = standardizeAD(source)
n = height(source);
core = table(source.Controller,source.Axis,source.SignedForce_N, ...
    source.Impulse_Ns,source.Outcome,source.Fell,source.Recovered, ...
    source.FirstEnvelopeEntryTime_s,source.RecoveryTime_s, ...
    source.PeakForceInducedAxisDisplacement_m, ...
    source.PeakForceInducedAxisTilt_deg, ...
    source.LateForceInducedAxisDisplacementRMS_m, ...
    source.LateForceInducedAxisTiltRMS_deg, ...
    source.LateForceInducedAxisVelocityRMS_m_s, ...
    source.AxisDisplacementLateEarlyRatio,source.AxisTiltLateEarlyRatio, ...
    source.ForceInducedPostureRMS_deg, ...
    source.MaxForceInducedJointDeviation_deg, ...
    source.PurePDTorqueRMS_Nm,source.PeakPurePDTorque_Nm, ...
    source.AppliedTorqueRMS_Nm,source.PeakAppliedTorque_Nm, ...
    zeros(n,1),zeros(n,1),zeros(n,1),source.ActuatorSaturation, ...
    'VariableNames',coreNames());
end

function core = standardizeRL(source)
n = height(source);
core = table(source.Controller,source.Axis,source.SignedForce_N, ...
    abs(source.SignedForce_N)*0.1,source.Outcome,source.Fell, ...
    source.Recovered,source.FirstEnvelopeEntryTime_s, ...
    source.RecoveryTime_s,source.PeakAxisDisplacement_m, ...
    source.PeakAxisTilt_deg,source.LateAxisDisplacementRMS_m, ...
    source.LateAxisTiltRMS_deg,source.LateAxisVelocityRMS_m_s, ...
    source.AxisDisplacementLateEarlyRatio,source.AxisTiltLateEarlyRatio, ...
    source.ForceInducedPostureRMS_deg, ...
    source.MaxForceInducedJointDeviation_deg, ...
    source.PurePDTorqueRMS_Nm,source.PeakPurePDTorque_Nm, ...
    source.AppliedTorqueRMS_Nm,source.PeakAppliedTorque_Nm, ...
    source.ResidualTorqueRMS_Nm,source.PeakResidualTorque_Nm, ...
    source.PeakNormalizedAction,source.ActuatorSaturation, ...
    'VariableNames',coreNames());
assert(n==14,"FinalBenchmark:UnexpectedRLCaseCount", ...
    "Expected 14 signed RL75 cases; received %d.",n);
end

