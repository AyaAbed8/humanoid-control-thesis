function results = run_model_uncertainty_study( ...
    trunkScaleFactors, lateralForce_N, sagittalForce_N, outputRoot)
%RUN_MODEL_UNCERTAINTY_STUDY Frozen A/D plant-model mismatch benchmark.
%   RESULTS = RUN_MODEL_UNCERTAINTY_STUDY() compares the nominal Simscape
%   plant with a +20 percent trunk mass/inertia case:
%
%     trunkScaleFactors = [1.0 1.2]
%     lateral force     = +/-50 N from 2.0 to 2.1 s
%     sagittal force    = +/-75 N from 2.0 to 2.1 s
%     stop time         = 11 s
%
%   The uncertainty is applied only to the Simscape Trunk File Solid by
%   multiplying its density. Geometry and centre of mass are unchanged, so
%   its mass and inertia scale together. The nominal rigidBodyTree used by
%   the Gravity Torque block is deliberately NOT changed. Controller A and
%   Controller D therefore remain frozen, and D experiences a genuine
%   plant-versus-controller model mismatch.
%
%   Two questions are separated:
%     1. Uncertainty-only: how does zero-force standing change relative to
%        the same controller on the nominal plant?
%     2. Combined robustness: under each plant scale, does the disturbed
%        response recover relative to that scale's matched zero-force run?
%
%   The selected +/-50 N lateral and +/-75 N sagittal pushes are inside
%   Controller A's established nominal-model recovery envelope while still
%   being informative for Controller D. This is a focused uncertainty
%   study, not a repetition of the complete force-envelope benchmark.
%
%   The Simulink model is changed only in memory. Its original Trunk
%   Density expression and dirty state are restored, and the model is never
%   saved by this function. The model is intentionally left open.

arguments
    trunkScaleFactors (1,:) double ...
        {mustBeFinite, mustBePositive} = [1 1.2]
    lateralForce_N (1,1) double ...
        {mustBeFinite, mustBePositive} = 50
    sagittalForce_N (1,1) double ...
        {mustBeFinite, mustBePositive} = 75
    outputRoot (1,1) string = ""
end

assert(any(abs(trunkScaleFactors - 1) < 1e-12), ...
    "ModelUncertainty:MissingNominalPlant", ...
    "trunkScaleFactors must include 1 for the nominal reference.");
assert(numel(unique(trunkScaleFactors)) == numel(trunkScaleFactors), ...
    "ModelUncertainty:DuplicateScale", ...
    "trunkScaleFactors must not contain duplicate values.");

model = "HumanoidModel_BaselineBalanceControl";
thisDirectory = string(project_codes_root());
modelFile = fullfile(thisDirectory, "models", model + ".slx");
assert(isfile(modelFile), "ModelUncertainty:ModelMissing", ...
    "Model not found: %s", modelFile);

originalDirectory = string(pwd);
directoryCleanup = onCleanup(@() cd(originalDirectory));
cd(thisDirectory);
load_system(model);

trunkBlock = model + "/Humanoid Robot/Torso and Head/Trunk";
assert(getSimulinkBlockHandle(trunkBlock) > 0, ...
    "ModelUncertainty:TrunkBlockMissing", ...
    "Expected Trunk File Solid block not found: %s", trunkBlock);
assert(strcmp(get_param(trunkBlock, "InertiaType"), ...
    "CalculateFromGeometry"), ...
    "ModelUncertainty:UnexpectedInertiaMode", ...
    "The Trunk block must calculate inertia from geometry and density.");

originalDensityExpression = string(get_param(trunkBlock, "Density"));
assert(originalDensityExpression == "trunkDensity", ...
    "ModelUncertainty:UnexpectedDensityExpression", ...
    "Expected nominal Trunk Density expression ""trunkDensity"", got ""%s"".", ...
    originalDensityExpression);
originalDirty = string(get_param(model, "Dirty"));
restoreCleanup = onCleanup(@() restoreModel( ...
    model, trunkBlock, originalDensityExpression, originalDirty));

if strlength(outputRoot) == 0
    outputRoot = fullfile(thisDirectory, "Results", ...
        "FormalModelUncertainty");
end
runStamp = string(datetime("now", "Format", "yyyyMMdd_HHmmss"));
resultDirectory = fullfile(outputRoot, runStamp);
mkdir(resultDirectory);

protocol = commonProtocol();
protocol.trunkScaleFactors = trunkScaleFactors;
protocol.uncertainQuantity = ...
    "Simscape Trunk density, hence Trunk mass and inertia";
protocol.controllerModelUpdated = false;
protocol.lateralForce_N = lateralForce_N;
protocol.sagittalForce_N = sagittalForce_N;

fprintf("\nFormal plant-model uncertainty study\n");
fprintf("Output: %s\n", resultDirectory);
fprintf("Trunk mass/inertia scale factors: %s\n", ...
    mat2str(trunkScaleFactors));
fprintf("Controller rigidBodyTree remains nominal: YES\n");
fprintf("Combined pushes: lateral +/-%.6g N, sagittal +/-%.6g N\n\n", ...
    lateralForce_N, sagittalForce_N);

batches = cell(numel(trunkScaleFactors), 2);
for scaleIndex = 1:numel(trunkScaleFactors)
    scale = trunkScaleFactors(scaleIndex);
    densityExpression = sprintf( ...
        "(%.17g)*(%s)", scale, originalDensityExpression);
    set_param(trunkBlock, "Density", densityExpression);
    fprintf("Plant scale %.6g: Trunk Density = %s\n", ...
        scale, densityExpression);

    scaleDirectory = fullfile(resultDirectory, ...
        "trunk_scale_" + scaleLabel(scale));
    lateralDirectory = fullfile(scaleDirectory, "lateral");
    sagittalDirectory = fullfile(scaleDirectory, "sagittal");

    batches{scaleIndex, 1} = calibrate_lateral_push_response( ...
        lateralForce_N, protocol.stopTime_s, lateralDirectory, ...
        protocol.pulseStart_s, protocol.pulseDuration_s);
    batches{scaleIndex, 2} = calibrate_sagittal_push_response( ...
        sagittalForce_N, protocol.stopTime_s, sagittalDirectory, ...
        protocol.pulseStart_s, protocol.pulseDuration_s);
end

nominalMetrics = makeNominalMetrics( ...
    batches, trunkScaleFactors, protocol);
pushMetrics = makePushMetrics( ...
    batches, trunkScaleFactors, lateralForce_N, ...
    sagittalForce_N, protocol);
summary = makeSummary(pushMetrics);

writetable(nominalMetrics, fullfile( ...
    resultDirectory, "uncertainty_only_metrics.csv"));
writetable(pushMetrics, fullfile( ...
    resultDirectory, "combined_push_metrics.csv"));
writetable(summary, fullfile( ...
    resultDirectory, "uncertainty_summary.csv"));
save(fullfile(resultDirectory, "processed_results.mat"), ...
    "nominalMetrics", "pushMetrics", "summary", ...
    "protocol", "batches", "model", "trunkBlock", ...
    "originalDensityExpression", "-v7.3");
writeProtocolText(resultDirectory, protocol, ...
    originalDensityExpression);

results = struct( ...
    "model", model, ...
    "resultDirectory", string(resultDirectory), ...
    "nominalMetrics", nominalMetrics, ...
    "pushMetrics", pushMetrics, ...
    "summary", summary, ...
    "protocol", protocol, ...
    "batches", {batches});

fprintf("\nUncertainty-only metrics:\n");
disp(nominalMetrics);
fprintf("\nCombined uncertainty-plus-push metrics:\n");
disp(pushMetrics);
fprintf("\nController/plant-scale summary:\n");
disp(summary);
fprintf("Results written to %s\n", resultDirectory);
end

function protocol = commonProtocol()
protocol = struct( ...
    "pulseStart_s", 2, ...
    "pulseDuration_s", 0.1, ...
    "stopTime_s", 11, ...
    "finalDwell_s", 2, ...
    "fallVerticalDrop_m", 0.5, ...
    "fallHorizontalTravel_m", 1, ...
    "fallRotation_deg", 30, ...
    "contactLoadThreshold_N", 1, ...
    "saturationTolerance_Nm", 1e-6, ...
    "recoveryDisplacementRMS_m", 0.025, ...
    "recoveryTiltRMS_deg", 2, ...
    "recoveryVelocityRMS_m_s", 0.02, ...
    "settlingRatioLimit", 0.75, ...
    "smallDisplacementRMS_m", 0.005, ...
    "smallTiltRMS_deg", 0.5);
end

function metrics = makeNominalMetrics(batches, scales, protocol)
nominalIndex = find(abs(scales - 1) < 1e-12, 1);
referenceA = batches{nominalIndex, 1}.trajectories{1};
referenceD = batches{nominalIndex, 1}.trajectories{4};
rows = cell(2 * numel(scales), 1);
rowIndex = 0;
for scaleIndex = 1:numel(scales)
    for controller = ["A", "D"]
        if controller == "A"
            trajectory = batches{scaleIndex, 1}.trajectories{1};
            reference = referenceA;
        else
            trajectory = batches{scaleIndex, 1}.trajectories{4};
            reference = referenceD;
        end
        rowIndex = rowIndex + 1;
        rows{rowIndex} = nominalComparison( ...
            trajectory, reference, controller, ...
            scales(scaleIndex), protocol);
    end
end
metrics = vertcat(rows{:});
end

function row = nominalComparison(trajectory, reference, ...
        controller, scale, p)
t = trajectory.qTime(:);
q = trajectory.q;
qReference = interpolateMatrix(reference.qTime, reference.q, t);
residual = q - qReference;
legResidual = residual(:, 11:22);

qInitial = q(1, :);
verticalDrop = max(qInitial(3) - q(:, 3));
horizontalTravel = max(vecnorm( ...
    q(:, 1:2) - qInitial(1:2), 2, 2));
rotationDeviation = max(abs(rad2deg( ...
    q(:, 4:6) - qInitial(4:6))), [], "all");
fell = verticalDrop > p.fallVerticalDrop_m || ...
    horizontalTravel > p.fallHorizontalTravel_m || ...
    rotationDeviation > p.fallRotation_deg;

late = t >= p.stopTime_s - p.finalDwell_s;
lateTranslationRMS = rmsAll(residual(late, 1:3));
lateRotationRMS = rad2deg(rmsAll(residual(late, 4:6)));
outcome = "upright";
if fell
    outcome = "fell";
end

row = table(controller, scale, 100 * (scale - 1), ...
    outcome, fell, ...
    rmsAll(residual(:, 1:3)), ...
    max(vecnorm(residual(:, 1:3), 2, 2)), ...
    rad2deg(rmsAll(residual(:, 4:6))), ...
    max(abs(rad2deg(residual(:, 4:6))), [], "all"), ...
    rmsAll(rad2deg(legResidual)), ...
    max(abs(rad2deg(legResidual)), [], "all"), ...
    lateTranslationRMS, lateRotationRMS, ...
    rmsAll(trajectory.pureTorque), ...
    max(abs(trajectory.pureTorque), [], "all"), ...
    rmsAll(trajectory.totalTorque), ...
    max(abs(trajectory.totalTorque), [], "all"), ...
    'VariableNames', {'Controller', 'TrunkMassInertiaScale', ...
    'TrunkMassInertiaChange_percent', 'Outcome', 'Fell', ...
    'TranslationDifferenceRMS_m', ...
    'PeakTranslationDifference_m', ...
    'RotationDifferenceRMS_deg', ...
    'PeakRotationDifference_deg', ...
    'LegPostureDifferenceRMS_deg', ...
    'PeakLegPostureDifference_deg', ...
    'LateTranslationDifferenceRMS_m', ...
    'LateRotationDifferenceRMS_deg', ...
    'PurePDTorqueRMS_Nm', 'PeakPurePDTorque_Nm', ...
    'AppliedTorqueRMS_Nm', 'PeakAppliedTorque_Nm'});
end

function metrics = makePushMetrics( ...
        batches, scales, lateralForce, sagittalForce, protocol)
rows = cell(8 * numel(scales), 1);
rowIndex = 0;
for scaleIndex = 1:numel(scales)
    lateral = batches{scaleIndex, 1};
    sagittal = batches{scaleIndex, 2};
    for item = [2 3 5 6]
        if item <= 3
            nominal = lateral.trajectories{1};
        else
            nominal = lateral.trajectories{4};
        end
        rowIndex = rowIndex + 1;
        rows{rowIndex} = classifyTrajectory( ...
            lateral.trajectories{item}, nominal, "lateral", ...
            lateralForce, scales(scaleIndex), protocol);
    end
    for item = [2 3 5 6]
        if item <= 3
            nominal = sagittal.trajectories{1};
        else
            nominal = sagittal.trajectories{4};
        end
        rowIndex = rowIndex + 1;
        rows{rowIndex} = classifyTrajectory( ...
            sagittal.trajectories{item}, nominal, "sagittal", ...
            sagittalForce, scales(scaleIndex), protocol);
    end
end
metrics = vertcat(rows{:});
end

function row = classifyTrajectory( ...
        disturbed, nominal, axisName, force, scale, p)
t = disturbed.qTime(:);
q = disturbed.q;
qNominal = interpolateMatrix(nominal.qTime, nominal.q, t);
qResidual = q - qNominal;
if axisName == "lateral"
    axisIndex = 1;
    tiltIndex = 5;
else
    axisIndex = 2;
    tiltIndex = 4;
end
axisResidual = qResidual(:, axisIndex);
tiltResidual = qResidual(:, tiltIndex);
legResidual = qResidual(:, 11:22);
velocityResidual = numericalDerivative(t, axisResidual);

pulseEnd = p.pulseStart_s + p.pulseDuration_s;
early = t >= pulseEnd & t <= pulseEnd + 2;
late = t >= p.stopTime_s - p.finalDwell_s;
earlyDisplacement = rmsAll(axisResidual(early));
lateDisplacement = rmsAll(axisResidual(late));
earlyTilt = rad2deg(rmsAll(tiltResidual(early)));
lateTilt = rad2deg(rmsAll(tiltResidual(late)));
displacementRatio = safeRatio( ...
    lateDisplacement, earlyDisplacement);
tiltRatio = safeRatio(lateTilt, earlyTilt);
lateVelocity = rmsAll(velocityResidual(late));

qInitial = q(1, :);
verticalDrop = max(qInitial(3) - q(:, 3));
horizontalTravel = max(vecnorm( ...
    q(:, 1:2) - qInitial(1:2), 2, 2));
rotationDeviation = max(abs(rad2deg( ...
    q(:, 4:6) - qInitial(4:6))), [], "all");
fallVertical = verticalDrop > p.fallVerticalDrop_m;
fallTravel = horizontalTravel > p.fallHorizontalTravel_m;
fallRotation = rotationDeviation > p.fallRotation_deg;
fell = fallVertical || fallTravel || fallRotation;

contactTime = disturbed.contactTime(:);
postContact = contactTime >= pulseEnd;
postRightLoad = disturbed.rightFootLoad(postContact);
postLeftLoad = disturbed.leftFootLoad(postContact);
bothUnloaded = disturbed.rightFootLoad(:) <= ...
    p.contactLoadThreshold_N & disturbed.leftFootLoad(:) <= ...
    p.contactLoadThreshold_N & postContact;
contactLossDuration = maskDuration(contactTime, bothUnloaded);

torqueTime = disturbed.torqueTime(:);
saturated = any(abs(disturbed.totalTorque) >= ...
    100 - p.saturationTolerance_Nm, 2);
saturationDuration = maskDuration(torqueTime, saturated);

withinEnvelope = ...
    lateDisplacement <= p.recoveryDisplacementRMS_m && ...
    lateTilt <= p.recoveryTiltRMS_deg && ...
    lateVelocity <= p.recoveryVelocityRMS_m_s;
displacementSettled = ...
    displacementRatio <= p.settlingRatioLimit || ...
    lateDisplacement <= p.smallDisplacementRMS_m;
tiltSettled = tiltRatio <= p.settlingRatioLimit || ...
    lateTilt <= p.smallTiltRMS_deg;
recovered = ~fell && withinEnvelope && ...
    displacementSettled && tiltSettled;
if fell
    outcome = "fell";
elseif recovered
    outcome = "recovered";
else
    outcome = "upright_not_recovered";
end

definition = disturbed.definition;
signedForce = force;
if contains(definition.Condition, "negative")
    signedForce = -force;
end
row = table(string(definition.Controller), scale, ...
    100 * (scale - 1), string(axisName), sign(signedForce), ...
    signedForce, abs(signedForce) * p.pulseDuration_s, ...
    outcome, fell, recovered, fallVertical, fallTravel, ...
    fallRotation, verticalDrop, horizontalTravel, ...
    rotationDeviation, any(bothUnloaded), contactLossDuration, ...
    any(saturated), saturationDuration, ...
    max(abs(axisResidual)), ...
    rad2deg(max(abs(tiltResidual))), ...
    lateDisplacement, lateTilt, lateVelocity, ...
    displacementRatio, tiltRatio, ...
    rmsAll(rad2deg(legResidual)), ...
    max(abs(rad2deg(legResidual)), [], "all"), ...
    rmsAll(disturbed.pureTorque), ...
    max(abs(disturbed.pureTorque), [], "all"), ...
    rmsAll(disturbed.totalTorque), ...
    max(abs(disturbed.totalTorque), [], "all"), ...
    min(postRightLoad), min(postLeftLoad), ...
    'VariableNames', {'Controller', 'TrunkMassInertiaScale', ...
    'TrunkMassInertiaChange_percent', 'Axis', 'DirectionSign', ...
    'SignedForce_N', 'Impulse_Ns', 'Outcome', 'Fell', ...
    'Recovered', 'FallByVerticalDrop', ...
    'FallByHorizontalTravel', 'FallByRotation', ...
    'PeakVerticalDrop_m', 'PeakHorizontalTravel_m', ...
    'PeakAbsoluteRotationDeviation_deg', ...
    'ContactLoss', 'ContactLossDuration_s', ...
    'ActuatorSaturation', 'ActuatorSaturationDuration_s', ...
    'PeakForceInducedAxisDisplacement_m', ...
    'PeakForceInducedAxisTilt_deg', ...
    'LateForceInducedAxisDisplacementRMS_m', ...
    'LateForceInducedAxisTiltRMS_deg', ...
    'LateForceInducedAxisVelocityRMS_m_s', ...
    'AxisDisplacementLateEarlyRatio', ...
    'AxisTiltLateEarlyRatio', ...
    'ForceInducedPostureRMS_deg', ...
    'MaxForceInducedJointDeviation_deg', ...
    'PurePDTorqueRMS_Nm', 'PeakPurePDTorque_Nm', ...
    'AppliedTorqueRMS_Nm', 'PeakAppliedTorque_Nm', ...
    'MinimumRightFootLoad_N', 'MinimumLeftFootLoad_N'});
end

function summary = makeSummary(metrics)
controllers = unique(metrics.Controller, "stable");
scales = unique(metrics.TrunkMassInertiaScale, "stable");
axes = unique(metrics.Axis, "stable");
rows = cell(numel(controllers) * numel(scales) * numel(axes), 1);
rowIndex = 0;
for controller = controllers'
    for scale = scales'
        for axisName = axes'
            selected = metrics.Controller == controller & ...
                metrics.TrunkMassInertiaScale == scale & ...
                metrics.Axis == axisName;
            rowIndex = rowIndex + 1;
            rows{rowIndex} = table(controller, scale, axisName, ...
                nnz(metrics.Outcome(selected) == "recovered"), ...
                nnz(metrics.Outcome(selected) == ...
                    "upright_not_recovered"), ...
                nnz(metrics.Outcome(selected) == "fell"), ...
                all(metrics.Recovered(selected)), ...
                any(metrics.ContactLoss(selected)), ...
                any(metrics.ActuatorSaturation(selected)), ...
                'VariableNames', {'Controller', ...
                'TrunkMassInertiaScale', 'Axis', ...
                'RecoveredCaseCount', ...
                'UprightNotRecoveredCaseCount', ...
                'FallCaseCount', ...
                'BidirectionallyRecovered', ...
                'AnyContactLoss', 'AnyActuatorSaturation'});
        end
    end
end
summary = vertcat(rows{:});
end

function writeProtocolText(directory, protocol, densityExpression)
file = fopen(fullfile(directory, "protocol.txt"), "w");
assert(file >= 0, "ModelUncertainty:ProtocolWriteFailed", ...
    "Could not create protocol.txt.");
cleanup = onCleanup(@() fclose(file));
fprintf(file, "Formal plant-model uncertainty study\n");
fprintf(file, "Nominal Trunk Density expression: %s\n", ...
    densityExpression);
fprintf(file, "Trunk mass/inertia scales: %s\n", ...
    mat2str(protocol.trunkScaleFactors));
fprintf(file, "Controller rigidBodyTree updated: false\n");
fprintf(file, "Lateral force: +/-%.17g N\n", ...
    protocol.lateralForce_N);
fprintf(file, "Sagittal force: +/-%.17g N\n", ...
    protocol.sagittalForce_N);
fprintf(file, "Pulse: %.17g to %.17g s\n", ...
    protocol.pulseStart_s, ...
    protocol.pulseStart_s + protocol.pulseDuration_s);
fprintf(file, "Stop time: %.17g s\n", protocol.stopTime_s);
fprintf(file, "Matched nominal subtraction: same controller and same plant scale\n");
end

function restoreModel(model, trunkBlock, densityExpression, dirtyState)
if bdIsLoaded(model)
    set_param(trunkBlock, "Density", densityExpression);
    if dirtyState == "off"
        set_param(model, "Dirty", "off");
    end
end
end

function label = scaleLabel(scale)
label = replace(compose("%.3f", scale), ".", "p");
end

function output = interpolateMatrix(sourceTime, values, targetTime)
if isequal(sourceTime, targetTime)
    output = values;
else
    output = interp1(sourceTime, values, targetTime, ...
        "linear", "extrap");
end
end

function derivative = numericalDerivative(time, values)
if numel(time) < 2
    derivative = zeros(size(values));
else
    derivative = gradient(values, time);
end
end

function duration = maskDuration(time, mask)
if numel(time) < 2 || ~any(mask)
    duration = 0;
else
    duration = trapz(time, double(mask));
end
end

function ratio = safeRatio(numerator, denominator)
if denominator <= 1e-12
    ratio = double(numerator > 1e-12) * Inf;
    if numerator <= 1e-12
        ratio = 0;
    end
else
    ratio = numerator / denominator;
end
end

function value = rmsAll(values)
value = sqrt(mean(values.^2, "all"));
end
