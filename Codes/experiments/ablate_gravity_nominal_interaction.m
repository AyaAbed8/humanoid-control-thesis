function effects = calculateEffects(metrics)
metricNames = ["PostureRMSError_deg", "MaxJointDeviation_deg", ...
    "NominalTargetRMSError_deg", "MaxNominalTargetError_deg", ...
    "FullReferenceTrackingRMSError_deg", ...
    "MaxFullReferenceTrackingError_deg", ...
    "NominalTorqueRMS_Nm", "PeakNominalTorque_Nm", ...
    "PurePDTorqueRMS_Nm", "PeakPurePDTorque_Nm", ...
    "DampingTorqueRMS_Nm", "PeakDampingTorque_Nm", ...
    "PreSaturationTorqueRMS_Nm", "PeakPreSaturationTorque_Nm", ...
    "PDNomTorqueRMS_Nm", "GravityTorqueRMS_Nm", ...
    "TotalTorqueRMS_Nm", "PeakTotalTorque_Nm", ...
    "AbsTorqueImpulse_Nms", "TorsoYRMSError_m", ...
    "TorsoYMaxDeviation_m"];
a = metrics(metrics.Case == "A", :);
b = metrics(metrics.Case == "B", :);
c = metrics(metrics.Case == "C", :);
d = metrics(metrics.Case == "D", :);
effects = table(metricNames.', 'VariableNames', {'Metric'});
effects.GravityAtOriginal_BminusA = difference(b, a, metricNames).';
effects.RetuningAtAlpha0_CminusA = difference(c, a, metricNames).';
effects.GravityAtRetuned_DminusC = difference(d, c, metricNames).';
effects.RetuningAtAlpha1_DminusB = difference(d, b, metricNames).';
effects.Interaction_DminusC_minus_BminusA = ...
    (difference(d, c, metricNames) - difference(b, a, metricNames)).';
end

function values = difference(first, second, names)
values = zeros(1, numel(names));
for index = 1:numel(names)
    values(index) = first.(names(index)) - second.(names(index));
end
end

function [time, values] = loggedMatrix(logs, name, expectedBlock)
matches = [];
for index = 1:logs.numElements
    element = logs.getElement(index);
    if strcmp(string(element.Name), name) && ...
            (strlength(expectedBlock) == 0 || ...
            strcmp(elementBlockPath(element), expectedBlock))
        matches(end + 1) = index; %#ok<AGROW>
    end
end
assert(~isempty(matches), "FourCaseAblation:LogMissing", ...
    "Log '%s' from '%s' was not found.", name, expectedBlock);
element = logs.getElement(matches(1));
[time, values] = valueToMatrix(element.Values, name);
end

function path = elementBlockPath(element)
path = "";
try
    blockPath = element.BlockPath;
    path = string(blockPath.getBlock(blockPath.getLength));
catch
end
end

function [time, values] = valueToMatrix(value, label)
if isa(value, "timeseries")
    time = double(value.Time(:));
    values = squeeze(double(value.Data));
    if numel(time) == 1
        values = reshape(values, 1, []);
    elseif isvector(values)
        values = values(:);
    elseif size(values, 1) ~= numel(time) && ...
            size(values, 2) == numel(time)
        values = values.';
    end
    return;
end
if isstruct(value)
    fields = fieldnames(value);
    assert(~isempty(fields), "FourCaseAblation:EmptyStruct", ...
        "Log '%s' is empty.", label);
    first = value.(fields{1});
    time = double(first.Time(:));
    values = zeros(numel(time), numel(fields));
    for index = 1:numel(fields)
        signal = value.(fields{index});
        data = squeeze(double(signal.Data));
        data = data(:);
        values(:, index) = interpolateMatrix( ...
            double(signal.Time(:)), data, time);
    end
    return;
end
error("FourCaseAblation:UnsupportedLog", ...
    "Log '%s' has unsupported type '%s'.", label, class(value));
end

function values = requireWidth(values, width, label)
assert(size(values, 2) == width, "FourCaseAblation:WrongWidth", ...
    "%s has %d columns; expected %d.", label, size(values, 2), width);
end

function angles = selectLegAngles(angles)
if size(angles, 2) == 22
    angles = angles(:, 11:22);
elseif size(angles, 2) ~= 12
    error("FourCaseAblation:AngleWidth", ...
        "Joint-angle log has %d columns; expected 12 or 22.", ...
        size(angles, 2));
end
end

function values = sensingToControllerOrder(values)
% Existing Joint Angles / Joint Angular Rates bus order:
% RH frontal, LH frontal, RH transverse, LH transverse, RH sagittal,
% LH sagittal, RA pitch, LA pitch, RA roll, LA roll, RK, LK.
% Convert to the validated controller torque-bus order.
indices = [1 11 7 5 3 9 2 12 8 6 4 10];
values = values(:, indices);
end

function output = interpolateMatrix(time, values, targetTime)
if isequal(time, targetTime)
    output = values;
elseif numel(time) == 1
    output = repmat(values(1, :), numel(targetTime), 1);
else
    output = interp1(time, values, targetTime, "linear", "extrap");
end
end

function value = rmsAll(values)
value = sqrt(mean(values.^2, "all"));
end

function values = columnRMS(matrix)
values = sqrt(mean(matrix.^2, 1)).';
end

function values = columnPeak(matrix)
values = max(abs(matrix), [], 1).';
end

function value = absoluteImpulse(time, torque)
if numel(time) < 2
    value = 0;
else
    value = trapz(time, sum(abs(torque), 2));
end
end

