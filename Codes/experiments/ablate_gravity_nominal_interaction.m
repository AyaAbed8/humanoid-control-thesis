function results = ablate_gravity_nominal_interaction( ...
    nominalFraction, stopTime, outputRoot)
%ABLATE_GRAVITY_NOMINAL_INTERACTION Four-case Controller C ablation.
%   RESULTS = ABLATE_GRAVITY_NOMINAL_INTERACTION() runs:
%     A: alpha=0, original nominal commands (frozen PD-only baseline)
%     B: alpha=1, original nominal commands (gravity only)
%     C: alpha=0, retuned nominal commands (nominal retuning only)
%     D: alpha=1, retuned nominal commands (Controller C)
%
%   The default retuned-command fraction is 1.15, selected by the revised
%   narrow Controller C sweep after correcting hip-sagittal control. Outer
%   feedback gains, inner joint stiffness
%   and damping, model settings, initial conditions, logging, and metric
%   calculations are identical in all four cases. Experimental values are
%   supplied through Simulink.SimulationInput; the saved model is unchanged.
%
%   The script also reports factorial effects for each numeric metric:
%     Gravity_at_original = B - A
%     Retuning_at_alpha0  = C - A
%     Gravity_at_retuned  = D - C
%     Retuning_at_alpha1  = D - B
%     Interaction         = (D - C) - (B - A)
%
%   Joint velocities are logged from the existing Joint Angular Rates line
%   by an in-memory logging change. The saved SLX file is never saved or
%   modified. Nominal, balance-feedback, damping, pre-saturation, and
%   post-saturation torques are reconstructed offline from the logged
%   signals and the controller parameters.

arguments
    nominalFraction (1,1) double {mustBeFinite, mustBeNonnegative} = 1.15
    stopTime (1,1) double = NaN
    outputRoot (1,1) string = ""
end

model = "HumanoidModel_BaselineBalanceControl";
thisDirectory = string(project_codes_root());
originalDirectory = string(pwd);
directoryCleanup = onCleanup(@() cd(originalDirectory)); %#ok<NASGU>
cd(thisDirectory);

variablesBeforeSetup = who;
humanoid_walker_parameters;
setupVariables = setdiff(who, variablesBeforeSetup);
robotFull = build_manual_humanoid_tree_BFreversed();
setupVariables = [setupVariables; {"robotFull"}];
setupData = struct();
for index = 1:numel(setupVariables)
    setupData.(setupVariables{index}) = eval(setupVariables{index});
end

load_system(model);
% Leave the model open for post-run inspection.
rateLoggingCleanup = enableRuntimeJointRateLogging(model); %#ok<NASGU>
controllerGainPath = model + "/Gain";
gravityGainPath = model + "/Gain2";
if isnan(stopTime)
    stopTime = str2double(get_param(model, "StopTime"));
end
assert(isfinite(stopTime) && stopTime > 0, ...
    "FourCaseAblation:InvalidStopTime", ...
    "Stop time must be a positive finite scalar.");

if strlength(outputRoot) == 0
    outputRoot = fullfile(thisDirectory, "Results", ...
        "GravityNominalFourCaseAblation");
end
runStamp = string(datetime("now", "Format", "yyyyMMdd_HHmmss"));
resultDirectory = fullfile(outputRoot, runStamp);
if ~isfolder(resultDirectory)
    mkdir(resultDirectory);
end

baseNominal = struct("hip", u_hip_frontal, "knee", u_knee, ...
    "ankle", u_ankle_pitch, "hipSagittal", u_hip_sagittal);

% Probe alpha=1 only at the initial sample. The logged vector is already in
% the validated 12-joint controller order and includes the sign mapping.
probeOutput = runCase(model, controllerGainPath, gravityGainPath, ...
    setupData, 1, baseNominal, min(stopTime, 1e-3));
[~, initialGravity] = loggedMatrix(probeOutput.logsout, ...
    "diag_tau_gravity_scaled", model + "/Gain2");
initialGravity = requireWidth(initialGravity, 12, ...
    "diag_tau_gravity_scaled");
initialGravity = initialGravity(1, :);
[fullCorrection, correctionDiagnostics] = nominalCorrection( ...
    initialGravity, params);
retunedNominal = applyCorrection( ...
    baseNominal, fullCorrection, nominalFraction);
validateNominal(retunedNominal);

definitions = table( ...
    ["A"; "B"; "C"; "D"], ...
    ["baseline"; "gravity_only"; "retuning_only"; "controller_c"], ...
    [0; 1; 0; 1], [false; false; true; true], ...
    repmat(nominalFraction, 4, 1), ...
    'VariableNames', {'Case', 'Description', 'Alpha', ...
    'UsesRetunedNominal', 'RetunedNominalFraction'});

fprintf("\nGravity x nominal-command four-case ablation\n");
fprintf("Model: %s\nStop time: %.6g s\n", model, stopTime);
fprintf("Retuned nominal fraction: %.6g\nResults: %s\n\n", ...
    nominalFraction, resultDirectory);
fprintf("Full normalized nominal correction " + ...
    "[hip knee ankle hip-sagittal]:\n");
disp([fullCorrection.hip, fullCorrection.knee, ...
    fullCorrection.ankle, fullCorrection.hipSagittal]);

outputs = cell(4, 1);
trajectories = cell(4, 1);
metricRows = cell(4, 1);
jointMetricRows = cell(4, 1);
for index = 1:4
    if definitions.UsesRetunedNominal(index)
        nominal = retunedNominal;
    else
        nominal = baseNominal;
    end
    fprintf("[%s] %s: alpha=%g, retuned nominal=%d\n", ...
        definitions.Case(index), definitions.Description(index), ...
        definitions.Alpha(index), definitions.UsesRetunedNominal(index));
    outputs{index} = runCase(model, controllerGainPath, ...
        gravityGainPath, setupData, definitions.Alpha(index), ...
        nominal, stopTime);
    [metricRows{index}, trajectories{index}, jointMetricRows{index}] = ...
        processCase(outputs{index}, definitions(index, :), stopTime, ...
        nominal, params);
end

metrics = vertcat(metricRows{:});
jointMetrics = vertcat(jointMetricRows{:});
effects = calculateEffects(metrics);

writetable(definitions, fullfile(resultDirectory, ...
    "case_definitions.csv"));
writetable(metrics, fullfile(resultDirectory, ...
    "four_case_metrics.csv"));
writetable(jointMetrics, fullfile(resultDirectory, ...
    "component_joint_metrics.csv"));
writetable(effects, fullfile(resultDirectory, ...
    "factorial_effects.csv"));
save(fullfile(resultDirectory, "processed_results.mat"), ...
    "metrics", "jointMetrics", "effects", "trajectories", "definitions", ...
    "initialGravity", "fullCorrection", "correctionDiagnostics", ...
    "baseNominal", "retunedNominal", "nominalFraction", "stopTime");
save(fullfile(resultDirectory, "raw_simulation_outputs.mat"), ...
    "outputs", "probeOutput", "-v7.3");
createPlots(metrics, resultDirectory);

results = struct("resultDirectory", string(resultDirectory), ...
    "metrics", metrics, "jointMetrics", jointMetrics, "effects", effects, ...
    "definitions", definitions, "baseNominal", baseNominal, ...
    "retunedNominal", retunedNominal, ...
    "fullNominalCorrection", fullCorrection, ...
    "correctionDiagnostics", correctionDiagnostics, ...
    "trajectories", {trajectories});

fprintf("\nFour-case metrics:\n");
disp(metrics);
fprintf("\nFactorial effects (signed differences):\n");
disp(effects);
fprintf("Results written to %s\n", resultDirectory);
end

function cleanup = enableRuntimeJointRateLogging(model)
% The line already exists inside the sensing subsystem. Changing its
% logging properties dirties only the loaded in-memory model; the onCleanup
% in the caller closes it with save=false.
rateOutport = model + "/Subsystem/Joint Angular Rates";
assert(getSimulinkBlockHandle(rateOutport) ~= -1, ...
    "FourCaseAblation:RateOutportMissing", ...
    "Existing Joint Angular Rates outport was not found.");
portHandles = get_param(rateOutport, "PortHandles");
lineHandle = get_param(portHandles.Inport, "Line");
assert(lineHandle ~= -1, "FourCaseAblation:RateLineMissing", ...
    "Joint Angular Rates outport has no connected input line.");
sourcePort = get_param(lineHandle, "SrcPortHandle");
assert(sourcePort ~= -1, "FourCaseAblation:RateSourceMissing", ...
    "Joint Angular Rates line has no source port.");
originalLogging = get_param(sourcePort, "DataLogging");
originalNameMode = get_param(sourcePort, "DataLoggingNameMode");
originalName = get_param(sourcePort, "DataLoggingName");
originalDirty = get_param(model, "Dirty");
set_param(sourcePort, "DataLogging", "on", ...
    "DataLoggingNameMode", "Custom", ...
    "DataLoggingName", "diag_joint_rates");
cleanup = onCleanup(@() restoreRateLogging( ...
    model, sourcePort, originalLogging, originalNameMode, ...
    originalName, originalDirty));
end

function restoreRateLogging(model, sourcePort, logging, nameMode, ...
        name, originalDirty)
set_param(sourcePort, "DataLogging", logging, ...
    "DataLoggingNameMode", nameMode, ...
    "DataLoggingName", name);
if strcmp(originalDirty, "off")
    set_param(model, "Dirty", "off");
end
end

function output = runCase(model, controllerGainPath, gravityGainPath, ...
    setupData, alpha, nominal, duration)
simIn = Simulink.SimulationInput(model);
names = fieldnames(setupData);
for index = 1:numel(names)
    simIn = simIn.setVariable(names{index}, setupData.(names{index}));
end
simIn = simIn.setVariable("alpha", alpha);
simIn = simIn.setVariable("robustnessForceVector_N", zeros(3, 1));
simIn = simIn.setVariable("u_hip_frontal", nominal.hip);
simIn = simIn.setVariable("u_knee", nominal.knee);
simIn = simIn.setVariable("u_ankle_pitch", nominal.ankle);
simIn = simIn.setVariable("u_hip_sagittal", nominal.hipSagittal);
simIn = simIn.setBlockParameter(controllerGainPath, "Gain", "1");
simIn = simIn.setBlockParameter(gravityGainPath, "Gain", "alpha");
simIn = simIn.setModelParameter("StopTime", num2str(duration, 17), ...
    "SignalLogging", "on", "SignalLoggingName", "logsout", ...
    "UnconnectedInputMsg", "none", ...
    "UnconnectedOutputMsg", "none", ...
    "UnconnectedLineMsg", "none");
output = sim(simIn);
assert(any(strcmp(output.who, "logsout")), ...
    "FourCaseAblation:NoLogsout", "Simulation produced no logsout.");
end

function [correction, diagnostics] = nominalCorrection(gravity, params)
% Torque bus order:
% RH frontal, RK, RA pitch, RH sagittal, RH transverse, RA roll,
% LH frontal, LK, LA pitch, LH sagittal, LH transverse, LA roll.
pairs = [1 7; 2 8; 3 9; 4 10];
pairedGravity = [mean(gravity(pairs(1, :))), ...
    mean(gravity(pairs(2, :))), mean(gravity(pairs(3, :))), ...
    mean(gravity(pairs(4, :)))];
sideDifferences = [diff(gravity(pairs(1, :))), ...
    diff(gravity(pairs(2, :))), diff(gravity(pairs(3, :))), ...
    diff(gravity(pairs(4, :)))];
ranges = [ ...
    (params.jointLimits.hipFrontalUpperLimit - ...
        params.jointLimits.hipFrontalLowerLimit) / 2, ...
    (params.jointLimits.kneeUpperLimit - ...
        params.jointLimits.kneeLowerLimit) / 2, ...
    (params.jointLimits.ankleUpperLimit - ...
        params.jointLimits.ankleLowerLimit) / 2, ...
    (params.jointLimits.hipSagittalUpperLimit - ...
        params.jointLimits.hipSagittalLowerLimit) / 2];
stiffness = [params.controller.hipFrontalStiffness, ...
    params.controller.kneeStiffness, ...
    params.controller.ankleStiffness, ...
    params.controller.hipSagittalStiffness];
shift = -pairedGravity ./ (stiffness .* deg2rad(ranges));
correction = struct("hip", shift(1), "knee", shift(2), ...
    "ankle", shift(3), "hipSagittal", shift(4));
diagnostics = struct("pairedGravityTorque_Nm", pairedGravity, ...
    "leftRightDifference_Nm", sideDifferences, ...
    "maxLeftRightDifference_Nm", max(abs(sideDifferences)), ...
    "unmatchedGravityChannels_Nm", gravity([5 6 11 12]));
end

function nominal = applyCorrection(base, correction, fraction)
nominal = struct("hip", base.hip + fraction * correction.hip, ...
    "knee", base.knee + fraction * correction.knee, ...
    "ankle", base.ankle + fraction * correction.ankle, ...
    "hipSagittal", ...
        base.hipSagittal + fraction * correction.hipSagittal);
end

function validateNominal(nominal)
values = [nominal.hip, nominal.knee, nominal.ankle, ...
    nominal.hipSagittal];
assert(all(isfinite(values)) && all(abs(values) <= 1), ...
    "FourCaseAblation:InvalidNominal", ...
    "Retuned normalized commands must be finite and within [-1,1].");
end

function [row, trajectory, jointMetrics] = processCase( ...
    output, definition, stopTime, nominal, params)
logs = output.logsout;
[pureTime, pure] = loggedMatrix(logs, "Pure PD Torques", "");
[controllerTime, controller] = loggedMatrix(logs, ...
    "PD+NOM Torques", ...
    "HumanoidModel_BaselineBalanceControl/Joint Control");
[gravityTime, gravity] = loggedMatrix(logs, ...
    "diag_tau_gravity_scaled", ...
    "HumanoidModel_BaselineBalanceControl/Gain2");
[totalTime, total] = loggedMatrix(logs, ...
    "diag_tau_leg_command", ...
    "HumanoidModel_BaselineBalanceControl/Final Actuator Torque Saturation");
[unsaturatedTime, unsaturatedTotal] = loggedMatrix(logs, ...
    "diag_tau_total_unsaturated", ...
    "HumanoidModel_BaselineBalanceControl/Sum");
[angleTime, angles] = loggedMatrix(logs, ...
    "confirm_joint_angles", "");
[rateTime, rates] = loggedMatrix(logs, "diag_joint_rates", "");
[torsoTime, torsoY] = loggedMatrix(logs, "torso_y", "");

pure = requireWidth(pure, 12, "Pure PD Torques");
controller = requireWidth(controller, 12, "PD+NOM Torques");
gravity = requireWidth(gravity, 12, "diag_tau_gravity_scaled");
total = requireWidth(total, 12, "diag_tau_leg_command");
unsaturatedTotal = requireWidth( ...
    unsaturatedTotal, 12, "diag_tau_total_unsaturated");
angles = sensingToControllerOrder(selectLegAngles(angles));
rates = sensingToControllerOrder(requireWidth( ...
    rates, 12, "diag_joint_rates"));
torsoY = torsoY(:, 1);

pure = interpolateMatrix(pureTime, pure, totalTime);
controller = interpolateMatrix(controllerTime, controller, totalTime);
gravity = interpolateMatrix(gravityTime, gravity, totalTime);
unsaturatedTotal = interpolateMatrix( ...
    unsaturatedTime, unsaturatedTotal, totalTime);
angles = interpolateMatrix(angleTime, angles, totalTime);
rates = interpolateMatrix(rateTime, rates, totalTime);
torsoY = interpolateMatrix(torsoTime, torsoY, totalTime);

[stiffness, damping, torqueLimit, controlled] = ...
    controllerParameterVectors(params);
nominalU = [nominal.hip, nominal.knee, nominal.ankle, ...
    nominal.hipSagittal, 0, 0, ...
    nominal.hip, nominal.knee, nominal.ankle, ...
    nominal.hipSagittal, 0, 0];
[rangeHalf, midpoint] = controllerAngleMapping(params);
nominalTarget = deg2rad(nominalU .* rangeHalf + midpoint);
nominalTarget(~controlled) = 0;

nominalError = nominalTarget - angles;
nominalError(:, ~controlled) = 0;
nominalTorque = nominalError .* stiffness;
balanceTorque = pure;
balanceTorque(:, ~controlled) = 0;
dampingTorque = -rates .* damping;
dampingTorque(:, ~controlled) = 0;
preSaturationTorque = nominalTorque + balanceTorque + dampingTorque;
postSaturationTorque = min(max( ...
    preSaturationTorque, -torqueLimit), torqueLimit);

fullReferenceError = nominalError;
fullReferenceError(:, controlled) = ...
    nominalError(:, controlled) + ...
    balanceTorque(:, controlled) ./ stiffness(controlled);
fullReferenceError(:, ~controlled) = 0;

controllerClosure = controller - postSaturationTorque;
saturationDifference = postSaturationTorque - preSaturationTorque;
saturated = abs(saturationDifference) > 1e-10;
angleDeviation = angles - angles(1, :);
torsoDeviation = torsoY - torsoY(1);
unsaturatedClosure = unsaturatedTotal - controller - gravity;
finalTorqueLimit = params.torqueLimits.legActuator;
expectedApplied = min(max( ...
    unsaturatedTotal, -finalTorqueLimit), finalTorqueLimit);
finalSaturationDifference = expectedApplied - unsaturatedTotal;
finalSaturated = abs(finalSaturationDifference) > 1e-10;
closure = total - expectedApplied;
finalTime = totalTime(end);

row = [definition, table(finalTime, ...
    finalTime >= stopTime - max(1e-8, 1e-6 * stopTime), ...
    rmsAll(rad2deg(angleDeviation)), ...
    max(abs(rad2deg(angleDeviation)), [], "all"), ...
    rmsAll(rad2deg(nominalError(:, controlled))), ...
    max(abs(rad2deg(nominalError(:, controlled))), [], "all"), ...
    rmsAll(rad2deg(fullReferenceError(:, controlled))), ...
    max(abs(rad2deg(fullReferenceError(:, controlled))), [], "all"), ...
    rmsAll(nominalTorque), max(abs(nominalTorque), [], "all"), ...
    rmsAll(pure), max(abs(pure), [], "all"), ...
    rmsAll(dampingTorque), max(abs(dampingTorque), [], "all"), ...
    rmsAll(preSaturationTorque), ...
    max(abs(preSaturationTorque), [], "all"), ...
    rmsAll(controller), rmsAll(gravity), rmsAll(total), ...
    max(abs(total), [], "all"), absoluteImpulse(totalTime, total), ...
    max(abs(controllerClosure), [], "all"), ...
    any(saturated, "all"), ...
    100 * mean(any(saturated, 2)), ...
    max(abs(saturationDifference), [], "all"), ...
    any(finalSaturated, "all"), ...
    100 * mean(any(finalSaturated, 2)), ...
    max(abs(finalSaturationDifference), [], "all"), ...
    max(abs(unsaturatedClosure), [], "all"), ...
    max(abs(closure), [], "all"), rmsAll(torsoDeviation), ...
    max(abs(torsoDeviation)), ...
    'VariableNames', {'FinalTime_s', 'ReachedStopTime', ...
    'PostureRMSError_deg', 'MaxJointDeviation_deg', ...
    'NominalTargetRMSError_deg', 'MaxNominalTargetError_deg', ...
    'FullReferenceTrackingRMSError_deg', ...
    'MaxFullReferenceTrackingError_deg', ...
    'NominalTorqueRMS_Nm', 'PeakNominalTorque_Nm', ...
    'PurePDTorqueRMS_Nm', 'PeakPurePDTorque_Nm', ...
    'DampingTorqueRMS_Nm', 'PeakDampingTorque_Nm', ...
    'PreSaturationTorqueRMS_Nm', 'PeakPreSaturationTorque_Nm', ...
    'PDNomTorqueRMS_Nm', 'GravityTorqueRMS_Nm', ...
    'TotalTorqueRMS_Nm', 'PeakTotalTorque_Nm', ...
    'AbsTorqueImpulse_Nms', 'ControllerClosureMaxError_Nm', ...
    'AnySaturation', 'SaturatedSamplePercent', ...
    'MaxSaturationCorrection_Nm', ...
    'AnyFinalActuatorSaturation', ...
    'FinalActuatorSaturatedSamplePercent', ...
    'MaxFinalActuatorSaturationCorrection_Nm', ...
    'UnsaturatedTorqueClosureMaxError_Nm', ...
    'TorqueClosureMaxError_Nm', ...
    'TorsoYRMSError_m', 'TorsoYMaxDeviation_m'})];
trajectory = struct("definition", definition, "time", totalTime, ...
    "purePDTorque", pure, "pdNomTorque", controller, ...
    "gravityTorque", gravity, "totalTorque", total, ...
    "unsaturatedTotalTorque", unsaturatedTotal, ...
    "jointAngles", angles, "jointRates", rates, ...
    "nominalTarget", nominalTarget, ...
    "nominalTargetError", nominalError, ...
    "fullReferenceTrackingError", fullReferenceError, ...
    "nominalTorque", nominalTorque, ...
    "balanceTorque", balanceTorque, ...
    "dampingTorque", dampingTorque, ...
    "preSaturationTorque", preSaturationTorque, ...
    "postSaturationTorque", postSaturationTorque, ...
    "controllerClosure", controllerClosure, ...
    "saturationDifference", saturationDifference, ...
    "finalSaturationDifference", finalSaturationDifference, ...
    "finalSaturated", finalSaturated, ...
    "unsaturatedTorqueClosure", unsaturatedClosure, ...
    "torsoY", torsoY);

jointNames = controllerJointNames();
jointMetrics = table( ...
    repmat(definition.Case, 12, 1), jointNames, controlled.', ...
    columnRMS(rad2deg(nominalError)), ...
    columnPeak(rad2deg(nominalError)), ...
    columnRMS(rad2deg(fullReferenceError)), ...
    columnPeak(rad2deg(fullReferenceError)), ...
    columnRMS(nominalTorque), columnPeak(nominalTorque), ...
    columnRMS(balanceTorque), columnPeak(balanceTorque), ...
    columnRMS(dampingTorque), columnPeak(dampingTorque), ...
    columnRMS(preSaturationTorque), columnPeak(preSaturationTorque), ...
    columnRMS(controller), columnPeak(controller), ...
    columnRMS(gravity), columnPeak(gravity), ...
    columnRMS(total), columnPeak(total), ...
    100 * mean(saturated, 1).', ...
    100 * mean(finalSaturated, 1).', ...
    'VariableNames', {'Case', 'Joint', 'StiffnessControlled', ...
    'NominalTargetErrorRMS_deg', 'NominalTargetErrorPeak_deg', ...
    'FullReferenceErrorRMS_deg', 'FullReferenceErrorPeak_deg', ...
    'NominalTorqueRMS_Nm', 'NominalTorquePeak_Nm', ...
    'BalanceTorqueRMS_Nm', 'BalanceTorquePeak_Nm', ...
    'DampingTorqueRMS_Nm', 'DampingTorquePeak_Nm', ...
    'PreSaturationTorqueRMS_Nm', 'PreSaturationTorquePeak_Nm', ...
    'PostSaturationTorqueRMS_Nm', 'PostSaturationTorquePeak_Nm', ...
    'GravityTorqueRMS_Nm', 'GravityTorquePeak_Nm', ...
    'TotalTorqueRMS_Nm', 'TotalTorquePeak_Nm', ...
    'SaturatedSamplePercent', ...
    'FinalActuatorSaturatedSamplePercent'});
end

function [stiffness, damping, torqueLimit, controlled] = ...
        controllerParameterVectors(params)
hipK = params.controller.hipFrontalStiffness;
hipSagittalK = params.controller.hipSagittalStiffness;
kneeK = params.controller.kneeStiffness;
ankleK = params.controller.ankleStiffness;
hipD = params.controller.hipFrontalDamping;
hipSagittalD = params.controller.hipSagittalDamping;
kneeD = params.controller.kneeDamping;
ankleD = params.controller.ankleDamping;
hipLimit = params.torqueLimits.hipFrontal;
hipSagittalLimit = params.torqueLimits.hipSagittal;
kneeLimit = params.torqueLimits.knee;
ankleLimit = params.torqueLimits.ankle;
stiffness = [hipK, kneeK, ankleK, hipSagittalK, 0, 0, ...
    hipK, kneeK, ankleK, hipSagittalK, 0, 0];
damping = [hipD, kneeD, ankleD, hipSagittalD, 0, 0, ...
    hipD, kneeD, ankleD, hipSagittalD, 0, 0];
torqueLimit = [hipLimit, kneeLimit, ankleLimit, ...
    hipSagittalLimit, 0, 0, hipLimit, kneeLimit, ankleLimit, ...
    hipSagittalLimit, 0, 0];
controlled = stiffness > 0;
end

function [rangeHalf, midpoint] = controllerAngleMapping(params)
hipUpper = params.jointLimits.hipFrontalUpperLimit;
hipLower = params.jointLimits.hipFrontalLowerLimit;
kneeUpper = params.jointLimits.kneeUpperLimit;
kneeLower = params.jointLimits.kneeLowerLimit;
ankleUpper = params.jointLimits.ankleUpperLimit;
ankleLower = params.jointLimits.ankleLowerLimit;
hipSagittalUpper = params.jointLimits.hipSagittalUpperLimit;
hipSagittalLower = params.jointLimits.hipSagittalLowerLimit;
hipRange = (hipUpper - hipLower) / 2;
kneeRange = (kneeUpper - kneeLower) / 2;
ankleRange = (ankleUpper - ankleLower) / 2;
hipSagittalRange = (hipSagittalUpper - hipSagittalLower) / 2;
hipMid = (hipUpper + hipLower) / 2;
kneeMid = (kneeUpper + kneeLower) / 2;
ankleMid = (ankleUpper + ankleLower) / 2;
hipSagittalMid = (hipSagittalUpper + hipSagittalLower) / 2;
rangeHalf = [hipRange, kneeRange, ankleRange, hipSagittalRange, ...
    0, 0, hipRange, kneeRange, ankleRange, hipSagittalRange, 0, 0];
midpoint = [hipMid, kneeMid, ankleMid, hipSagittalMid, ...
    0, 0, hipMid, kneeMid, ankleMid, hipSagittalMid, 0, 0];
end

