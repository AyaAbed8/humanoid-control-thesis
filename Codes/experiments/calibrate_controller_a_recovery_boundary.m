function results = calibrate_controller_a_recovery_boundary( ...
    sagittalLevels_N, lateralLevels_N, outputRoot)
%CALIBRATE_CONTROLLER_A_RECOVERY_BOUNDARY Refine A's push boundary.
%   RESULTS = CALIBRATE_CONTROLLER_A_RECOVERY_BOUNDARY() performs a
%   focused, bidirectional extension of the completed force benchmark:
%
%     sagittal: +/-[80 85 90 95] N
%     lateral:  +/-[125 150] N
%
%   Rationale:
%     - A recovered bidirectionally at 75 N sagittally, but the +100 N
%       case was upright-not-recovered. The 80:5:95 grid refines that
%       transition without repeating the established endpoints.
%     - A recovered bidirectionally at the largest tested lateral force,
%       100 N. The 125 and 150 N cases test whether its lateral recovery
%       envelope extends farther.
%
%   Every signed condition uses Controller A, nominal plant scale, a
%   100 ms pulse starting at 2 s, and the existing 11 s recovery window.
%   The helper runs a matched zero-force reference before each requested
%   case, so each classification uses the same established recovery rules.
%
%   This is boundary characterisation, not RL training and not controller
%   retuning. The model is never saved.

arguments
    sagittalLevels_N (1,:) double ...
        {mustBeFinite, mustBePositive} = [80 85 90 95]
    lateralLevels_N (1,:) double ...
        {mustBeFinite, mustBePositive} = [125 150]
    outputRoot (1,1) string = ""
end

assert(numel(unique(sagittalLevels_N)) == ...
    numel(sagittalLevels_N), ...
    "BoundaryCalibration:DuplicateSagittalLevel", ...
    "Sagittal levels must not contain duplicates.");
assert(numel(unique(lateralLevels_N)) == ...
    numel(lateralLevels_N), ...
    "BoundaryCalibration:DuplicateLateralLevel", ...
    "Lateral levels must not contain duplicates.");

thisDirectory = string(project_codes_root());
if strlength(outputRoot) == 0
    outputRoot = fullfile(thisDirectory, "Results", ...
        "ControllerARecoveryBoundary");
end
runStamp = string(datetime("now", "Format", "yyyyMMdd_HHmmss"));
resultDirectory = fullfile(outputRoot, runStamp);
mkdir(resultDirectory);

axes = strings(0, 1);
forces = zeros(0, 1);
for level = sagittalLevels_N
    axes(end + 1:end + 2, 1) = "sagittal";
    forces(end + 1:end + 2, 1) = [level; -level];
end
for level = lateralLevels_N
    axes(end + 1:end + 2, 1) = "lateral";
    forces(end + 1:end + 2, 1) = [level; -level];
end
caseTable = table((1:numel(forces)).', axes, forces, ...
    'VariableNames', {'CaseNumber', 'Axis', 'SignedForce_N'});

fprintf("\nController A recovery-boundary calibration\n");
fprintf("Sagittal refinement: +/- %s N\n", ...
    mat2str(sagittalLevels_N));
fprintf("Lateral extension: +/- %s N\n", ...
    mat2str(lateralLevels_N));
fprintf("Cases: %d signed disturbances; output: %s\n\n", ...
    height(caseTable), resultDirectory);

metricRows = cell(height(caseTable), 1);
for caseIndex = 1:height(caseTable)
    definition = caseTable(caseIndex, :);
    fprintf("\n=== Boundary case %d/%d: %s, %+.6g N ===\n", ...
        caseIndex, height(caseTable), ...
        definition.Axis, definition.SignedForce_N);
    caseResult = run_specific_uncertainty_case( ...
        "A", 0, definition.Axis, ...
        definition.SignedForce_N, 11);
    metricRows{caseIndex} = caseResult.metrics;

    partialMetrics = vertcat(metricRows{1:caseIndex});
    writetable(partialMetrics, fullfile( ...
        resultDirectory, "boundary_metrics_partial.csv"));
    save(fullfile(resultDirectory, ...
        "boundary_checkpoint.mat"), ...
        "partialMetrics", "caseTable", ...
        "sagittalLevels_N", "lateralLevels_N");
end

metrics = vertcat(metricRows{:});
summary = makeSummary(metrics);
writetable(metrics, fullfile( ...
    resultDirectory, "boundary_metrics.csv"));
writetable(summary, fullfile( ...
    resultDirectory, "boundary_summary.csv"));
save(fullfile(resultDirectory, "processed_results.mat"), ...
    "metrics", "summary", "caseTable", ...
    "sagittalLevels_N", "lateralLevels_N");

results = struct( ...
    "resultDirectory", string(resultDirectory), ...
    "metrics", metrics, ...
    "summary", summary, ...
    "caseDefinitions", caseTable);

fprintf("\nBoundary metrics:\n");
disp(metrics(:, ["Axis", "SignedForce_N", "Outcome", ...
    "Fell", "Recovered", ...
    "LateForceInducedAxisDisplacementRMS_m", ...
    "LateForceInducedAxisTiltRMS_deg", ...
    "AxisDisplacementLateEarlyRatio", ...
    "AxisTiltLateEarlyRatio", ...
    "ActuatorSaturation"]));
fprintf("\nBidirectional summary for newly tested levels:\n");
disp(summary);
fprintf("Results written to %s\n", resultDirectory);
end

function summary = makeSummary(metrics)
axisColumn = strings(0, 1);
forceColumn = zeros(0, 1);
positiveOutcome = strings(0, 1);
negativeOutcome = strings(0, 1);
bidirectionalRecovered = false(0, 1);
for axisName = ["sagittal", "lateral"]
    levels = unique(abs(metrics.SignedForce_N( ...
        metrics.Axis == axisName)));
    for level = levels'
        selected = metrics.Axis == axisName & ...
            abs(metrics.SignedForce_N) == level;
        positive = selected & metrics.SignedForce_N > 0;
        negative = selected & metrics.SignedForce_N < 0;
        assert(nnz(positive) == 1 && nnz(negative) == 1, ...
            "BoundaryCalibration:IncompleteSignedPair", ...
            "Expected one positive and one negative %s case at %.6g N.", ...
            axisName, level);
        axisColumn(end + 1, 1) = axisName; %#ok<AGROW>
        forceColumn(end + 1, 1) = level; %#ok<AGROW>
        positiveOutcome(end + 1, 1) = ...
            metrics.Outcome(positive); %#ok<AGROW>
        negativeOutcome(end + 1, 1) = ...
            metrics.Outcome(negative); %#ok<AGROW>
        bidirectionalRecovered(end + 1, 1) = ...
            all(metrics.Recovered(selected)); %#ok<AGROW>
    end
end
summary = table(axisColumn, forceColumn, ...
    positiveOutcome, negativeOutcome, bidirectionalRecovered, ...
    'VariableNames', {'Axis', 'ForceMagnitude_N', ...
    'PositiveOutcome', 'NegativeOutcome', ...
    'BidirectionallyRecovered'});
end
