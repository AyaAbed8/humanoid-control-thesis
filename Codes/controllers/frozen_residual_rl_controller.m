% Release verification checks policy identity only here. The historical
% hashes remain provenance; they do not identify the later deployment model.
verify_release_deployment();
names = "agent";
absolute = struct();
for index = 1:numel(names)
    name = names(index);
    absolute.(name) = fullfile(thisDirectory, relative.(name));
    assert(isfile(absolute.(name)), ...
        "FrozenResidualRL:EvidenceMissing", ...
        "Frozen %s file is missing: %s", name, absolute.(name));
    actualHash = fileHash(absolute.(name));
    assert(actualHash == expected.(name), ...
        "FrozenResidualRL:HashMismatch", ...
        "Frozen %s hash changed.\nExpected: %s\nActual:   %s\nFile: %s", ...
        name, expected.(name), actualHash, absolute.(name));
end

