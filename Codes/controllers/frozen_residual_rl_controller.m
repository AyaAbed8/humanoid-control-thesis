%   Returns the exact RL75 policy selected after checkpoint screening and
%   the 11 s formal lateral-force comparison on 28 July 2026.
%   Release edition: verifies policy identity and current deployment hashes.
%   Historical experiment hashes below are provenance, not runtime gates.
%
%   Scientific comparison rule:
%     Do not change Controller A, the observation/reward definition, action
%     mapping, physical action bound, model or policy within an evaluation.
%     Any such change defines a new controller variant and requires separate
%     validation and labelling.

