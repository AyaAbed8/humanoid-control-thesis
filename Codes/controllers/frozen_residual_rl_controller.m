    "formalMetrics", ...
        "5D2575E4163CC8DDC2D9C0C7622D1A858DAFAD9703B42A646FC4B9DCF602E637", ...
    "model", ...
        "27702354E89CA7A87BA809894D74EDD480461586C843F6D7456F3F1053422170", ...
    "parameters", ...
        "F2F84C847BF4BE7F807AF5A03221C8B46D55AD0ED7169F0BE0013D4924D89673", ...
